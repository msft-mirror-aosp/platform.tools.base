package com.android.tools.render.discovery

import com.android.tools.render.StandaloneRenderModelModule
import com.android.tools.render.compose.ComposeScreenshot
import com.android.tools.render.validation.MethodLevelValidator
import org.objectweb.asm.AnnotationVisitor
import org.objectweb.asm.ClassReader
import org.objectweb.asm.ClassVisitor
import org.objectweb.asm.MethodVisitor
import org.objectweb.asm.Opcodes
import org.objectweb.asm.Type

/** Discovers Compose preview annotation parameters for a method from compiled bytecode. */
class PreviewDiscoveryEngine(private val module: StandaloneRenderModelModule) {

  private val methodLevelValidator = MethodLevelValidator()

  private val classLoader: ClassLoader
    get() = module.environment.moduleClassLoaderManager.getShared(this::class.java.classLoader).classLoader

  companion object {
    /** Maximum number of previews allowed to be discovered for a single method to prevent DAG exponential expansion. */
    private const val MAX_DISCOVERED_PREVIEWS = 100

    /** Descriptor for Jetpack Compose's `@Composable` annotation. */
    private const val COMPOSABLE_DESC = "Landroidx/compose/runtime/Composable;"

    private const val PREVIEW_DESC = "Landroidx/compose/ui/tooling/preview/Preview;"

    /**
     * Synthetic container annotation descriptor generated by the Kotlin/Java compiler when multiple repeatable `@Preview` annotations are
     * declared on the same method (e.g. `@Preview @Preview`).
     */
    private const val PREVIEW_CONTAINER_DESC = "Landroidx/compose/ui/tooling/preview/Preview\$Container;"

    /** Descriptor for Jetpack Compose's `@PreviewParameter` annotation. */
    private const val PREVIEW_PARAMETER_DESC = "Landroidx/compose/ui/tooling/preview/PreviewParameter;"

    /** Descriptor for Jetpack Compose's `@PreviewWrapper` annotation. */
    private const val PREVIEW_WRAPPER_DESC = "Landroidx/compose/ui/tooling/preview/PreviewWrapper;"

    /** Name of the attribute referencing the `PreviewWrapperProvider` class in `@PreviewWrapper`. */
    private const val PREVIEW_WRAPPER_ATTRIBUTE = "wrapper"
  }

  /**
   * Discovers all `@Preview` annotations declared on [methodFQN] from compiled bytecode.
   *
   * Evaluates each preview-annotated method overload independently (e.g. `MyPreview()` and
   * `MyPreview(@PreviewParameter(UserProvider::class) user: User)`), returning a separate [DiscoveredMethodPreviews] per overload.
   * Non-preview overloads are skipped.
   *
   * Supports single previews, repeatable multi-previews, custom MultiPreview class annotations, and parameter annotations such as
   * `@PreviewParameter` and `@PreviewWrapper`.
   */
  fun discoverAllPreviews(methodFQN: String, previewId: String? = null): List<DiscoveredMethodPreviews> {
    val className = methodFQN.substringBeforeLast(".")
    val methodName = methodFQN.substringAfterLast(".")

    val classBytes = findClassBytes(className) ?: return emptyList()

    val discoveryResults = mutableListOf<DiscoveredMethodPreviews>()
    val resolvedPreviewId = previewId ?: methodName

    val classReader = ClassReader(classBytes)
    classReader.accept(
      object : ClassVisitor(Opcodes.ASM9) {
        override fun visitMethod(
          access: Int,
          name: String,
          descriptor: String,
          signature: String?,
          exceptions: Array<out String>?,
        ): MethodVisitor? {
          if (name != methodName) return null
          if ((access and Opcodes.ACC_SYNTHETIC) != 0) return null

          var isComposable = false
          val previewParamsList = mutableListOf<Map<String, String>>()
          val previewParameterAttributes = mutableMapOf<String, String>()
          val traversalPath = mutableSetOf<String>()
          val discoveredWrappers = mutableListOf<String>()

          val onWrapperFound: (String) -> Unit = { wrapper -> discoveredWrappers.add(wrapper) }

          return object : MethodVisitor(Opcodes.ASM9) {
            override fun visitAnnotation(desc: String, visible: Boolean): AnnotationVisitor? {
              if (desc == COMPOSABLE_DESC) {
                isComposable = true
                return null
              }
              return handleAnnotation(desc, traversalPath, previewParamsList, onWrapperFound)
            }

            override fun visitParameterAnnotation(parameter: Int, desc: String, visible: Boolean): AnnotationVisitor? {
              if (desc == PREVIEW_PARAMETER_DESC) {
                return createPreviewParameterVisitor(previewParameterAttributes)
              }
              return null
            }

            override fun visitEnd() {
              if (previewParamsList.isEmpty() && discoveredWrappers.isEmpty()) {
                return // Skip non-preview methods.
              }

              val validationResult =
                methodLevelValidator.validate(methodFQN = methodFQN, isComposable = isComposable, previewParamsList = previewParamsList)

              if (validationResult.hasErrors) {
                discoveryResults.add(DiscoveredMethodPreviews(previews = emptyList(), methodValidationResult = validationResult))
                return
              }

              if (discoveredWrappers.size > 1) {
                throw IllegalStateException(
                  "Multiple @PreviewWrapper annotations found for method '$methodFQN': ${discoveredWrappers.joinToString(", ")}"
                )
              }
              val previewWrapperFqn = discoveredWrappers.singleOrNull()
              val methodParams = if (previewParameterAttributes.isNotEmpty()) listOf(previewParameterAttributes) else emptyList()
              val methodPreviews = mutableListOf<ComposeScreenshot>()
              for (previewParams in previewParamsList) {
                methodPreviews.add(
                  ComposeScreenshot(
                    methodFQN = methodFQN,
                    methodParams = methodParams,
                    previewParams = previewParams,
                    previewId = resolvedPreviewId,
                    previewWrapperFqn = previewWrapperFqn,
                  )
                )
              }
              discoveryResults.add(DiscoveredMethodPreviews(previews = methodPreviews, methodValidationResult = validationResult))
            }
          }
        }
      },
      ClassReader.SKIP_CODE or ClassReader.SKIP_DEBUG or ClassReader.SKIP_FRAMES,
    )

    return discoveryResults
  }

  /**
   * Routes an annotation [desc] encountered during traversal:
   * - Direct `@Preview`: Extracts its preview parameters.
   * - Repeatable `@Preview$Container`: Traverses the container array of `@Preview` annotations.
   * - Direct `@PreviewWrapper`: Extracts wrapper provider FQN.
   * - Custom MultiPreview: Recursively inspects the annotation class bytecode if [isPotentialMultiPreview] matches.
   */
  private fun handleAnnotation(
    desc: String,
    traversalPath: MutableSet<String>,
    discoveredList: MutableList<Map<String, String>>,
    onWrapperFound: (String) -> Unit,
  ): AnnotationVisitor? {
    if (discoveredList.size >= MAX_DISCOVERED_PREVIEWS) {
      return null
    }

    when (desc) {
      PREVIEW_DESC -> {
        val previewParams = mutableMapOf<String, String>()
        discoveredList.add(previewParams)
        return createPreviewAnnotationVisitor(previewParams)
      }
      PREVIEW_CONTAINER_DESC -> {
        return createPreviewContainerVisitor(discoveredList)
      }
      PREVIEW_WRAPPER_DESC -> {
        return createPreviewWrapperVisitor(onWrapperFound)
      }
      else -> {
        if (isPotentialMultiPreview(desc)) {
          val annotationClassName = Type.getType(desc).className
          discoverFromAnnotationClass(annotationClassName, traversalPath, discoveredList, onWrapperFound)
        }
        return null
      }
    }
  }

  /**
   * Loads bytecode for [annotationClassName] and traverses its class-level annotations to discover nested `@Preview` or MultiPreview
   * definitions. Tracks [traversalPath] on the active recursion call stack to safely prevent infinite recursion on circular references.
   */
  private fun discoverFromAnnotationClass(
    annotationClassName: String,
    traversalPath: MutableSet<String>,
    discoveredList: MutableList<Map<String, String>>,
    onWrapperFound: (String) -> Unit,
  ) {
    if (discoveredList.size >= MAX_DISCOVERED_PREVIEWS) {
      return
    }

    if (traversalPath.contains(annotationClassName)) {
      // Circular dependency detected on the active call stack (e.g. A -> B -> A)
      return
    }

    val classBytes = findClassBytes(annotationClassName) ?: return

    try {
      traversalPath.add(annotationClassName)
      val classReader = ClassReader(classBytes)
      classReader.accept(
        object : ClassVisitor(Opcodes.ASM9) {
          override fun visitAnnotation(desc: String, visible: Boolean): AnnotationVisitor? {
            return handleAnnotation(desc, traversalPath, discoveredList, onWrapperFound)
          }
        },
        ClassReader.SKIP_CODE or ClassReader.SKIP_DEBUG or ClassReader.SKIP_FRAMES,
      )
    } finally {
      traversalPath.remove(annotationClassName)
    }
  }

  /**
   * Creates an [AnnotationVisitor] to traverse the `value` array of a synthetic `@Preview$Container` annotation and extract all nested
   * `@Preview` annotations into [discoveredList].
   */
  private fun createPreviewContainerVisitor(discoveredList: MutableList<Map<String, String>>): AnnotationVisitor {
    return object : AnnotationVisitor(Opcodes.ASM9) {
      override fun visitArray(name: String?): AnnotationVisitor {
        return object : AnnotationVisitor(Opcodes.ASM9) {
          override fun visitAnnotation(name: String?, descriptor: String?): AnnotationVisitor? {
            if (discoveredList.size >= MAX_DISCOVERED_PREVIEWS) {
              return null
            }
            if (descriptor == PREVIEW_DESC) {
              val previewParams = mutableMapOf<String, String>()
              discoveredList.add(previewParams)
              return createPreviewAnnotationVisitor(previewParams)
            }
            return null
          }
        }
      }
    }
  }

  /**
   * Optimization to avoid loading and parsing bytecode for standard runtime, compiler, and framework annotations (e.g. `java.*`,
   * `kotlin.*`, `androidx.compose.runtime.*`) that can never lead to a MultiPreview definition.
   *
   * Matches the MultiPreview traversal filtering used in Android Studio (`couldBeMultiPreviewAnnotation`).
   */
  private fun isPotentialMultiPreview(desc: String): Boolean {
    return desc.startsWith("L") &&
      !desc.startsWith("Ljava/") &&
      !desc.startsWith("Ljavax/") &&
      !desc.startsWith("Lkotlin/") &&
      !desc.startsWith("Lkotlinx/") &&
      !desc.startsWith("Landroidx/compose/runtime/") &&
      !desc.startsWith("Landroidx/annotation/") &&
      !desc.startsWith("Lorg/intellij/") &&
      !desc.startsWith("Lorg/jetbrains/")
  }

  /**
   * Creates an [AnnotationVisitor] that extracts parameter key-value pairs from a `@Preview` annotation into the provided [previewParams]
   * map.
   */
  private fun createPreviewAnnotationVisitor(previewParams: MutableMap<String, String>): AnnotationVisitor {
    return object : AnnotationVisitor(Opcodes.ASM9) {
      override fun visit(name: String, value: Any) {
        previewParams[name] =
          when (value) {
            is Type -> value.className
            else -> value.toString()
          }
      }

      override fun visitEnum(name: String, descriptor: String?, value: String) {
        previewParams[name] = value
      }
    }
  }

  /** Creates an [AnnotationVisitor] that extracts attributes from a `@PreviewParameter` annotation. */
  private fun createPreviewParameterVisitor(paramMap: MutableMap<String, String>): AnnotationVisitor {
    return object : AnnotationVisitor(Opcodes.ASM9) {
      override fun visit(name: String, value: Any) {
        paramMap[name] =
          when (value) {
            is Type -> value.className
            else -> value.toString()
          }
      }
    }
  }

  /** Creates an [AnnotationVisitor] that extracts the wrapper provider class FQN from a `@PreviewWrapper` annotation. */
  private fun createPreviewWrapperVisitor(onWrapperFound: (String) -> Unit): AnnotationVisitor {
    return object : AnnotationVisitor(Opcodes.ASM9) {
      override fun visit(name: String, value: Any) {
        if (name == PREVIEW_WRAPPER_ATTRIBUTE && value is Type) {
          onWrapperFound(value.className)
        }
      }
    }
  }

  /**
   * Retrieves raw .class bytes from the [classLoader] for [className].
   *
   * Tries direct package path first (e.g. `com/example/MyClass.class`), then falls back to replacing dots with `$` from right to left to
   * support nested and companion classes (e.g. `MyClass$Companion.class`).
   */
  private fun findClassBytes(className: String): ByteArray? {
    // 1. First attempt: standard package path where all dots are package separators (com/example/MyClass.class)
    val directResource = "${className.replace('.', '/')}.class"
    classLoader.getResourceAsStream(directResource)?.use {
      return it.readBytes()
    }

    // 2. Fallback: handle inner/nested classes and companion objects by replacing dots with '$' from right to left
    // (e.g. "com.example.MyClass.Inner" -> "com/example/MyClass$Inner.class")
    var candidate = className
    while (candidate.contains('.')) {
      val idx = candidate.lastIndexOf('.')
      candidate = candidate.substring(0, idx) + "$" + candidate.substring(idx + 1)
      val resource = "${candidate.replace('.', '/')}.class"
      classLoader.getResourceAsStream(resource)?.use {
        return it.readBytes()
      }
    }
    return null
  }
}
