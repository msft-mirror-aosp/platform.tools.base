/**
 * Reports all `<uses-permission>` elements in the merged manifest that are blocked in a private compute core (PCC) process if:
 * - ALL components (activities, services, etc.) are marked as `isPrivateComputeCoreProcess="true"` (and there must be at least one
 *   component).
 *
 * We require all components to be marked as such because it is fine to use blocked permissions in non-PCC components, and, unfortunately,
 * `<uses-permission>` is "global" (does not just apply to a specific component).
 *
 * See [RestrictedEnvironmentBlockedCallDetector] for a check that is similar in spirit (but blocks method calls), but that can report more
 * liberally because it is disabled by default, and was to be enabled only in specific Gradle modules. A similar approach might work here,
 * if the approach of marking the entire Gradle module is possible in the future.
 */
class PrivateComputeCoreDetector : Detector(), XmlScanner {
  override fun checkMergedProject(context: Context) {
    val project = context.mainProject
    // We don't yet know how permissions that later become "allowed in private compute core" will work,
    // so we currently only handle targetSdkVersion 37 (until this is worked out by the feature team).
    if (project.targetSdk != 37) return
    val mergedManifest = project.mergedManifest?.documentElement ?: return
    val application = mergedManifest.subtag(TAG_APPLICATION) ?: return
    val components = application.iterator().asSequence().filter { it.tagName.isComponentTag }.toList()
    if (components.isEmpty()) return
    // _All_ components must be PCC components.
    if (components.any { component -> component.getAttributeNS(ANDROID_URI, ATTR_PCC_PROCESS) != VALUE_TRUE }) return
    for (permission in mergedManifest) {
      if (permission.tagName != TAG_USES_PERMISSION) continue
      val permissionName = permission.getAttributeNS(ANDROID_URI, ATTR_NAME).takeIf(CharSequence::isNotEmpty) ?: continue
      if (permissionName.isBlockedPrivateComputeCorePermission) {
        context.report(
          ISSUE,
          context.getLocation(permission),
          "Permission \"$permissionName\" is not allowed in private compute core process",
        )
      }
    }
  }

  companion object {
    @JvmField
    val ISSUE =
      Issue.create(
        id = "PrivateComputePermission",
        briefDescription = "Permission disallowed in private compute",
        explanation =
          """
          Only certain permissions are allowed in private compute core processes. \
          If all app components (activities, services, etc.) are marked as private compute core processes \
          then certain `<uses-permission>` tags are most likely a mistake.
          """,
        category = Category.CORRECTNESS,
        priority = 5,
        severity = Severity.WARNING,
        implementation = Implementation(PrivateComputeCoreDetector::class.java, Scope.MANIFEST_SCOPE),
        androidSpecific = true,
      )

    private const val ATTR_PCC_PROCESS = "isPrivateComputeCoreProcess"
  }
}

private val String.isComponentTag
  get() =
    when (this) {
      TAG_ACTIVITY,
      TAG_SERVICE,
      TAG_RECEIVER,
      TAG_PROVIDER -> true
      else -> false
    }

