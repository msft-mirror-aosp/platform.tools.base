package com.android.build.gradle.integration.api

import com.android.build.api.variant.ApplicationAndroidComponentsExtension
import com.android.build.gradle.integration.common.fixture.project.GradleRule
import com.android.build.gradle.integration.common.fixture.project.plugins.ApplicationComponentCallback
import com.android.build.gradle.internal.scope.InternalArtifactType
import com.google.common.truth.Truth
import java.io.File
import org.gradle.api.DefaultTask
import org.gradle.api.Project
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.tasks.OutputFile
import org.gradle.api.tasks.TaskAction
import org.junit.Rule
import org.junit.Test
import org.junit.runner.RunWith
import org.junit.runners.Parameterized

/**
 * Integration test for adding a generated manifest file to the Android Test sources.
 *
 * @param generateManifest true if a manifest should be generated by a task
 * @param inAndroidTest true if that manifest should be generated in the android test sourceset or false in the main sourceset.
 */
@RunWith(Parameterized::class)
class GeneratedManifestInAndroidTestTest(private val generateManifest: Boolean, private val inAndroidTest: Boolean) {

  companion object {

    @JvmStatic
    @Parameterized.Parameters(name = "generateManifest={0}, inAndroidTest={1}")
    fun parameters() = listOf(arrayOf(true, true), arrayOf(true, false), arrayOf(false, true), arrayOf(false, false))
  }

  @get:Rule
  val rule =
    GradleRule.from {
      androidApplication {
        android {
          namespace = "com.android.tests.basic"
          defaultConfig {
            versionCode = 12
            versionName = "2.0"
            minSdk = 16
            targetSdk = 16
            testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
          }
        }
        files {
          update("src/main/AndroidManifest.xml")
            .replaceWith(
              """
              <?xml version="1.0" encoding="utf-8"?>
              <manifest xmlns:android="http://schemas.android.com/apk/res/android">
                <application android:label="@string/app_name">
                </application>
              </manifest>
              """
                .trimIndent()
            )

          add(
            "src/androidTest/AndroidManifest.xml",
            """
            <?xml version="1.0" encoding="utf-8"?>
            <manifest xmlns:android="http://schemas.android.com/apk/res/android">
                <instrumentation android:name="${"$"}{instrumentationRunner}">
                    <meta-data android:name="listener"
                               android:value="androidx.test.internal.runner.listener.ManifestListener"/>
                </instrumentation>
            </manifest>
            """
              .trimIndent(),
          )

          add(
            "src/main/res/values/strings.xml",
            """
            <resources>
                <string name="app_name">ManifestInTest</string>
            </resources>
            """
              .trimIndent(),
          )

          add(
            "src/androidTest/res/values/strings.xml",
            """
            <?xml version="1.0" encoding="utf-8"?>
            <resources>
                <string name="app_name">_Test-Basic</string>
            </resources>
            """
              .trimIndent(),
          )
        }
        if (generateManifest) {
          pluginCallbacks += GenerateManifestInAndroidTestCallback::class.java
        }
      }
      // Pass inAndroidTest to the build via gradle properties for the callback
      gradleProperties { add("test.inAndroidTest", inAndroidTest.toString()) }
    }

  @Test
  fun testGeneratedManifestIsUsed() {

    fun checkManifest(manifest: File, presence: Boolean) {
      println("Checking manifest ${manifest.absolutePath}")
      Truth.assertThat(manifest.exists()).isTrue()
      val content = manifest.readText()
      if (presence) {
        Truth.assertThat(content).contains("android:name=\"foo.generated.SEND_TEXT\"")
      } else {
        Truth.assertThat(content).doesNotContain("android:name=\"foo.generated.SEND_TEXT\"")
      }
    }

    rule.build.executor.run("assembleDebugAndroidTest")
    val mainManifest =
      rule.build
        .androidApplication()
        .buildDir
        .resolve(
          "intermediates/" +
            InternalArtifactType.PACKAGED_MANIFESTS.getFolderName() +
            "/debug/processDebugManifestForPackage/AndroidManifest.xml"
        )
        .toFile()

    val androidTestManifest =
      rule.build
        .androidApplication()
        .buildDir
        .resolve(
          "intermediates/" +
            InternalArtifactType.PACKAGED_MANIFESTS.getFolderName() +
            "/debugAndroidTest/processDebugAndroidTestManifest/AndroidManifest.xml"
        )
        .toFile()

    if (generateManifest) {
      if (inAndroidTest) {
        checkManifest(androidTestManifest, true)

        // delete the user provided test manifest source file and make sure it still merges fine.
        rule.build.androidApplication().resolve("src/androidTest/AndroidManifest.xml").toFile().delete()
        rule.build.executor.run("clean", "assembleDebugAndroidTest")
        checkManifest(androidTestManifest, true)
      } else {
        checkManifest(mainManifest, true)
      }
    } else {
      checkManifest(mainManifest, false)
      checkManifest(androidTestManifest, false)
      Truth.assertThat(androidTestManifest.readText()).contains("instrumentation")
    }

    // ensure that sync models are built correctly
    rule.build.modelBuilder.fetchModels()
  }
}

abstract class GenerateCustomManifestTask : DefaultTask() {

  @get:OutputFile abstract val manifestProperty: RegularFileProperty

  @TaskAction
  fun generateManifest() {
    manifestProperty
      .get()
      .asFile
      .writeText(
        """
        <manifest xmlns:android="http://schemas.android.com/apk/res/android"
            android:versionCode="00000000"
            android:versionName="0.0.0">

            <permission
                android:name="foo.generated.SEND_TEXT"
                android:description="@string/app_name"
                android:label="@string/app_name"
                android:permissionGroup="foo.permission-group.COST_MONEY" />
        </manifest>
        """
          .trimIndent()
      )
  }
}

class GenerateManifestInAndroidTestCallback : ApplicationComponentCallback {

  override fun handleExtension(project: Project, androidComponents: ApplicationAndroidComponentsExtension) {
    val inAndroidTest = project.providers.gradleProperty("test.inAndroidTest").get().toBoolean()
    androidComponents.onVariants { variant ->
      val generateCustomManifestTask =
        project.tasks.register("generate${variant.name.capitalize()}CustomManifest", GenerateCustomManifestTask::class.java)
      if (inAndroidTest) {
        variant.androidTest
          ?.sources
          ?.manifests
          ?.addGeneratedManifestFile(generateCustomManifestTask, GenerateCustomManifestTask::manifestProperty)
      } else {
        variant.sources.manifests.addGeneratedManifestFile(generateCustomManifestTask, GenerateCustomManifestTask::manifestProperty)
      }
    }
  }
}
