package com.android.tools.utp.plugins.result.listener.gradle

import com.android.ddmlib.testrunner.TestIdentifier
import com.android.ddmlib.testrunner.XmlTestRunListener
import com.android.tools.utp.plugins.result.listener.gradle.proto.GradleAndroidTestResultListenerProto
import com.android.tools.utp.plugins.result.listener.gradle.proto.GradleAndroidTestResultListenerProto.TestResultEvent.StateCase
import com.google.protobuf.Any
import com.google.protobuf.Message
import com.google.testing.platform.proto.api.core.ErrorDetailProto
import com.google.testing.platform.proto.api.core.TestCaseProto
import com.google.testing.platform.proto.api.core.TestResultProto
import com.google.testing.platform.proto.api.core.TestStatusProto
import com.google.testing.platform.proto.api.core.TestSuiteResultProto

/**
 * Adapts Unified Test Platform (UTP) test result events into Ddmlib's [XmlTestRunListener] callbacks.
 *
 * This adapter allows consumers that rely on the Ddmlib listener interface to process results
 * generated by UTP.
 *
 * @property ddmlibTestRunName The name of the test run to report to the Ddmlib listener.
 * @property ddmlibTestResultListener The Ddmlib listener that will receive the translated events.
 */
class DdmlibTestResultAdapter(
    private val ddmlibTestRunName: String,
    private val ddmlibTestResultListener: XmlTestRunListener
) {

    private var numTestFails: Int = 0
    private var startTimestamp: Long = 0L

    fun onTestResultEvent(testResultEvent: GradleAndroidTestResultListenerProto.TestResultEvent) {
        when(testResultEvent.stateCase) {
            StateCase.TEST_SUITE_STARTED -> {
                startTimestamp = System.currentTimeMillis()
                val testSuite: TestSuiteResultProto.TestSuiteMetaData =
                    testResultEvent.testSuiteStarted.testSuiteMetadata.unpack()
                ddmlibTestResultListener.testRunStarted(
                    ddmlibTestRunName,
                    testSuite.scheduledTestCaseCount)
            }

            StateCase.TEST_CASE_STARTED -> {
                val testCase: TestCaseProto.TestCase =
                    testResultEvent.testCaseStarted.testCase.unpack()
                val testId = TestIdentifier(
                    "${testCase.testPackage}.${testCase.testClass}", testCase.testMethod)
                ddmlibTestResultListener.testStarted(testId)
            }

            StateCase.TEST_CASE_FINISHED -> {
                val testResult: TestResultProto.TestResult =
                    testResultEvent.testCaseFinished.testCaseResult.unpack()
                val testId = TestIdentifier(
                    "${testResult.testCase.testPackage}.${testResult.testCase.testClass}",
                    testResult.testCase.testMethod)

                when(testResult.testStatus) {
                    TestStatusProto.TestStatus.FAILED, TestStatusProto.TestStatus.ERROR -> {
                        ddmlibTestResultListener.testFailed(testId, testResult.error.stackTrace)
                        ++numTestFails
                    }
                    TestStatusProto.TestStatus.IGNORED -> {
                        ddmlibTestResultListener.testIgnored(testId)
                    }
                    else -> {}
                }
                ddmlibTestResultListener.testEnded(testId, mapOf())
            }

            StateCase.TEST_SUITE_FINISHED -> {
                if (numTestFails > 0) {
                    ddmlibTestResultListener.testRunFailed("There was $numTestFails failure(s).")
                }
                val testSuiteResult: TestSuiteResultProto.TestSuiteResult =
                    testResultEvent.testSuiteFinished.testSuiteResult.unpack()
                if (testSuiteResult.platformError.errorsCount > 0) {
                    ddmlibTestResultListener.addSystemError(
                        getPlatformErrorMessage(testSuiteResult) + "\n"
                    )
                }
                testSuiteResult.issueList.forEach { issue ->
                    ddmlibTestResultListener.addSystemError(issue.message + "\n")
                }
                ddmlibTestResultListener.testRunEnded(
                    System.currentTimeMillis() - startTimestamp,
                    mapOf()
                )
            }

            else -> {}
        }
    }
}

private inline fun <reified T : Message> Any.unpack(): T = unpack(T::class.java)

private const val UNKNOWN_PLATFORM_ERROR_MESSAGE =
    "Unknown platform error occurred when running the UTP test suite. Please check logs for details."

/**
 * Finds the root cause of the Platform Error and returns the error message.
 */
fun getPlatformErrorMessage(resultsProto: TestSuiteResultProto.TestSuiteResult?): String {
    resultsProto ?: return UNKNOWN_PLATFORM_ERROR_MESSAGE
    return resultsProto.platformError.errorsList.joinToString(
        "\n", transform = ::getPlatformErrorMessage)
}

/**
 * Finds the root cause of the Platform Error and returns the error message.
 *
 * @param error the top level error detail to be analyzed.
 */
private fun getPlatformErrorMessage(
    error : ErrorDetailProto.ErrorDetail,
    errorMessageBuilder: StringBuilder = StringBuilder()) : StringBuilder {
    if (error.hasCause()) {
        if (error.summary.errorMessage.isNotBlank()) {
            errorMessageBuilder.append("${error.summary.errorMessage}\n")
        }
        getPlatformErrorMessage(error.cause, errorMessageBuilder)
    } else {
        if (error.summary.errorMessage.isNotBlank()) {
            errorMessageBuilder.append("${error.summary.errorMessage}\n")
        } else {
            errorMessageBuilder.append("$UNKNOWN_PLATFORM_ERROR_MESSAGE\n")
        }
        errorMessageBuilder.append(error.summary.stackTrace)
    }
    return errorMessageBuilder
}
