#ifndef COVERAGE_PARAMETER_SHIFTER_H_
#define COVERAGE_PARAMETER_SHIFTER_H_

#include <vector>
#include "slicer/code_ir.h"
#include "slicer/dex_ir.h"
#include "tools/base/android-test/coverage/common/log.h"

namespace coverage {

class ParameterShifter {
 public:
  // Performs low-level parameter relocation (prologue moves) to safely shift
  // shifted argument registers back to their expected original slots,
  // satisfying the verifier and ensuring method arguments are correctly aligned
  // inside expanded frames.
  //
  // NOTE: Why we use our own custom parameter shifting instead of Slicer's
  // 'AllocateScratchRegs': Slicer's native 'AllocateScratchRegs' allocator
  // employs an aggressive, global register renumbering/renaming pass when it
  // needs to expand the register frame. While mathematically elegant, this
  // wholesale register renumbering is highly prone to violating strict JVM/ART
  // verifier boundaries on complex methods (such as those generated by Jetpack
  // Compose). It frequently triggers Out-of-Bounds registers or invalid
  // parameter VerifyErrors that crash the app at startup.
  //
  // To ensure 100% verifier safety, we bypass Slicer's allocator and perform
  // surgical frame expansion (registers += 1) coupled with this manual,
  // lightweight prologue-shifting loop. We copy incoming arguments from their
  // shifted slots (reg) back to their expected slots (reg - 1) before the main
  // method body starts, leaving the entire rest of the method's instructions
  // completely pristine.
  static bool ShiftParameters(
      ir::EncodedMethod* ir_method, lir::CodeIr& code_ir,
      const std::vector<lir::Instruction*>& super_calls);
};

}  // namespace coverage

#endif  // COVERAGE_PARAMETER_SHIFTER_H_
